-- Planner nutrition quality and explainable-personalization foundation.
-- Clinical/dietary classifications inferred from text are intentionally marked
-- PENDING_REVIEW and must not be presented as medical advice.
alter table
    public.planner_meals
add
    column if not exists fiber_grams numeric(10, 2),
add
    column if not exists sugar_grams numeric(10, 2),
add
    column if not exists sodium_mg numeric(10, 2),
add
    column if not exists saturated_fat_grams numeric(10, 2),
add
    column if not exists serving_size numeric(10, 2),
add
    column if not exists serving_unit varchar(30),
add
    column if not exists nutrition_data_quality varchar(20) not null default 'UNVERIFIED',
add
    column if not exists nutrition_source varchar(255);

do $ $ begin if not exists (
    select
        1
    from
        pg_constraint
    where
        conname = 'ck_planner_meals_extended_nutrition'
) then
alter table
    public.planner_meals
add
    constraint ck_planner_meals_extended_nutrition check (
        (
            fiber_grams is null
            or fiber_grams >= 0
        )
        and (
            sugar_grams is null
            or sugar_grams >= 0
        )
        and (
            sodium_mg is null
            or sodium_mg >= 0
        )
        and (
            saturated_fat_grams is null
            or saturated_fat_grams >= 0
        )
        and (
            serving_size is null
            or serving_size > 0
        )
    );

end if;

if not exists (
    select
        1
    from
        pg_constraint
    where
        conname = 'ck_planner_meals_nutrition_quality'
) then
alter table
    public.planner_meals
add
    constraint ck_planner_meals_nutrition_quality check (
        nutrition_data_quality in ('UNVERIFIED', 'ESTIMATED', 'VERIFIED')
    );

end if;

end $ $;

create table if not exists public.diet_types (
    diet_type_id integer generated by default as identity primary key,
    code varchar(40) not null unique,
    name_en varchar(100) not null,
    name_km varchar(150),
    description_en text,
    is_active boolean not null default true,
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6) not null default current_timestamp
);

create table if not exists public.planner_meal_diet_types (
    planner_meal_id integer not null references public.planner_meals(planner_meal_id) on delete cascade,
    diet_type_id integer not null references public.diet_types(diet_type_id) on delete cascade,
    classification_source varchar(20) not null default 'MANUAL',
    review_status varchar(20) not null default 'VERIFIED',
    created_at timestamp(6) not null default current_timestamp,
    primary key (planner_meal_id, diet_type_id),
    constraint ck_meal_diet_source check (
        classification_source in ('MANUAL', 'AUTO_KEYWORD', 'IMPORTED')
    ),
    constraint ck_meal_diet_review check (
        review_status in ('PENDING_REVIEW', 'VERIFIED', 'REJECTED')
    )
);

create table if not exists public.allergens (
    allergen_id integer generated by default as identity primary key,
    code varchar(40) not null unique,
    name_en varchar(100) not null,
    name_km varchar(150),
    is_active boolean not null default true,
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6) not null default current_timestamp
);

create table if not exists public.planner_meal_allergens (
    planner_meal_id integer not null references public.planner_meals(planner_meal_id) on delete cascade,
    allergen_id integer not null references public.allergens(allergen_id) on delete cascade,
    presence_status varchar(20) not null default 'MAY_CONTAIN',
    classification_source varchar(20) not null default 'MANUAL',
    review_status varchar(20) not null default 'VERIFIED',
    created_at timestamp(6) not null default current_timestamp,
    primary key (planner_meal_id, allergen_id),
    constraint ck_meal_allergen_presence check (presence_status in ('CONTAINS', 'MAY_CONTAIN')),
    constraint ck_meal_allergen_source check (
        classification_source in ('MANUAL', 'AUTO_KEYWORD', 'IMPORTED')
    ),
    constraint ck_meal_allergen_review check (
        review_status in ('PENDING_REVIEW', 'VERIFIED', 'REJECTED')
    )
);

create table if not exists public.health_conditions (
    health_condition_id integer generated by default as identity primary key,
    code varchar(50) not null unique,
    name_en varchar(120) not null,
    name_km varchar(180),
    disclaimer_en text not null,
    is_active boolean not null default true,
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6) not null default current_timestamp
);

create table if not exists public.planner_meal_health_guidance (
    planner_meal_id integer not null references public.planner_meals(planner_meal_id) on delete cascade,
    health_condition_id integer not null references public.health_conditions(health_condition_id) on delete cascade,
    guidance_level varchar(20) not null,
    rationale_en text not null,
    evidence_url varchar(500),
    review_status varchar(20) not null default 'PENDING_REVIEW',
    reviewed_by varchar(150),
    reviewed_at timestamp(6),
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6) not null default current_timestamp,
    primary key (planner_meal_id, health_condition_id),
    constraint ck_meal_health_guidance_level check (
        guidance_level in ('PREFER', 'NEUTRAL', 'LIMIT', 'AVOID')
    ),
    constraint ck_meal_health_guidance_review check (
        review_status in (
            'PENDING_REVIEW',
            'CLINICIAN_VERIFIED',
            'REJECTED'
        )
    )
);

create table if not exists public.meal_plan_feedback (
    meal_plan_feedback_id integer generated by default as identity primary key,
    meal_plan_id integer not null references public.meal_plans(meal_plan_id) on delete cascade,
    user_id integer not null references public.users(user_id) on delete cascade,
    rating smallint,
    outcome varchar(20) not null,
    skip_reason varchar(80),
    hunger_before smallint,
    fullness_after smallint,
    comment_text varchar(500),
    created_at timestamp(6) not null default current_timestamp,
    updated_at timestamp(6) not null default current_timestamp,
    constraint uk_meal_plan_feedback_user unique (meal_plan_id, user_id),
    constraint ck_meal_feedback_rating check (
        rating is null
        or rating between 1
        and 5
    ),
    constraint ck_meal_feedback_outcome check (
        outcome in ('EATEN', 'PARTIALLY_EATEN', 'SKIPPED')
    ),
    constraint ck_meal_feedback_hunger check (
        hunger_before is null
        or hunger_before between 1
        and 5
    ),
    constraint ck_meal_feedback_fullness check (
        fullness_after is null
        or fullness_after between 1
        and 5
    )
);

create table if not exists public.meal_recommendation_audits (
    recommendation_audit_id bigint generated by default as identity primary key,
    user_id integer not null references public.users(user_id) on delete cascade,
    planner_meal_id integer not null references public.planner_meals(planner_meal_id) on delete cascade,
    weight_goal varchar(30) not null,
    total_score numeric(10, 4) not null,
    nutrition_score numeric(10, 4),
    preference_score numeric(10, 4),
    adherence_score numeric(10, 4),
    diversity_score numeric(10, 4),
    explanation_en text,
    explanation_km text,
    input_snapshot jsonb not null default '{}' :: jsonb,
    model_version varchar(50) not null,
    created_at timestamp(6) not null default current_timestamp,
    constraint ck_recommendation_audit_goal check (
        weight_goal in ('LOSE_WEIGHT', 'MAINTAIN_HEALTH', 'GAIN_WEIGHT')
    )
);

create table if not exists public.nutrition_evidence_sources (
