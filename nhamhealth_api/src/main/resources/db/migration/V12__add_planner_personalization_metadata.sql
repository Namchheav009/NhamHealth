-- All active meals are candidates for a balanced pattern. Keyword-derived
-- vegetarian/vegan labels remain pending review so the UI can distinguish
-- inference from verified dietary classification.
insert into
    public.planner_meal_diet_types (
        planner_meal_id,
        diet_type_id,
        classification_source,
        review_status
    )
select
    pm.planner_meal_id,
    dt.diet_type_id,
    'AUTO_KEYWORD',
    'PENDING_REVIEW'
from
    public.planner_meals pm
    join public.diet_types dt on dt.code = 'BALANCED'
where
    pm.is_active = true on conflict (planner_meal_id, diet_type_id) do nothing;

insert into
    public.planner_meal_diet_types (
        planner_meal_id,
        diet_type_id,
        classification_source,
        review_status
    )
select
    pm.planner_meal_id,
    dt.diet_type_id,
    'AUTO_KEYWORD',
    'PENDING_REVIEW'
from
    public.planner_meals pm
    join public.diet_types dt on dt.code = 'HIGH_PROTEIN'
where
    pm.is_active = true
    and pm.protein_grams >= 25 on conflict (planner_meal_id, diet_type_id) do nothing;

-- Conservative allergen candidates inferred from English ingredient/name text.
-- MAY_CONTAIN + PENDING_REVIEW prevents unsafe use as a definitive allergy label.
with meal_text as (
    select
        planner_meal_id,
        lower(
            concat_ws(' ', name_en, ingredients_text, tags_text)
        ) as searchable
    from
        public.planner_meals
    where
        is_active = true
),
candidates as (
    select
        planner_meal_id,
        'MILK' as code
    from
        meal_text
    where
        searchable ~ '(milk|yogurt|cheese|butter|cream)'
    union
    select
        planner_meal_id,
        'EGG'
    from
        meal_text
    where
        searchable ~ '(^|[^a-z])egg([^a-z]|$)'
    union
    select
        planner_meal_id,
        'PEANUT'
    from
        meal_text
    where
        searchable ~ 'peanut'
    union
    select
        planner_meal_id,
        'TREE_NUT'
    from
        meal_text
    where
        searchable ~ '(almond|cashew|walnut|pistachio|hazelnut|mixed nuts| nuts)'
    union
    select
        planner_meal_id,
        'SOY'
    from
        meal_text
    where
        searchable ~ '(soy|tofu|tempeh)'
    union
    select
        planner_meal_id,
        'WHEAT'
    from
        meal_text
    where
        searchable ~ '(wheat|bread|pasta|noodle|flour|toast)'
    union
    select
        planner_meal_id,
        'FISH'
    from
        meal_text
    where
        searchable ~ '(fish|salmon|tuna|sardine|mackerel)'
    union
    select
        planner_meal_id,
        'SHELLFISH'
    from
        meal_text
    where
        searchable ~ '(shrimp|prawn|crab|lobster|shellfish)'
    union
    select
        planner_meal_id,
        'SESAME'
    from
        meal_text
    where
        searchable ~ '(sesame|tahini)'
)
insert into
    public.planner_meal_allergens (
        planner_meal_id,
        allergen_id,
        presence_status,
        classification_source,
        review_status
    )
select
    c.planner_meal_id,
    a.allergen_id,
    'MAY_CONTAIN',
    'AUTO_KEYWORD',
    'PENDING_REVIEW'
from
    candidates c
    join public.allergens a on a.code = c.code on conflict (planner_meal_id, allergen_id) do nothing;

