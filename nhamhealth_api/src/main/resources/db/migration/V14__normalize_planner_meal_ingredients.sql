        ) as unit
    from
        raw_parts
    where
        raw_value <> ''
),
resolved as (
    select
        parsed.*,
        ingredient.ingredient_id,
        row_number() over (
            partition by parsed.planner_meal_id,
            ingredient.ingredient_id
            order by
                parsed.display_order
        ) as duplicate_number
    from
        parsed
        join lateral (
            select
                i.ingredient_id
            from
                public.ingredients i
            where
                lower(i.ingredient_name) = lower(parsed.ingredient_name)
            order by
                i.ingredient_id
            limit
                1
        ) ingredient on true
    where
        parsed.ingredient_name <> ''
)
insert into
    public.planner_meal_ingredients (
        planner_meal_id,
        ingredient_id,
        quantity,
        unit,
        display_order
    )
select
    planner_meal_id,
    ingredient_id,
    quantity,
    unit,
    row_number() over (
        partition by planner_meal_id
        order by
            display_order
    ) :: integer
from
    resolved
where
    duplicate_number = 1 on conflict do nothing;
